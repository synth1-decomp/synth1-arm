CSynthWin::CSynthWin()
{
}

CSynthWin::CSynthWin(void* pAU)
{
    m_pAU = pAU;
    m_winType = CCWIN_CUSTOM;
    m_pUser = NULL;
}

CSynthWin::~CSynthWin()
{
    if (m_pUser) {
        exitCapture(m_pUser);
        m_pUser = NULL;
    }
}

void CSynthWin::onCreate(HWND hWnd, CSynthesizer1* pSynth)
{
    m_hWnd = hWnd;
    m_pSynth = pSynth;
    pSynth->setSynWin(hWnd);
    g_bTransparencyWin = getIniInt("transparencywin", 1);
    constructPanel(hWnd);
    m_guis.drawAll();
    drawAllParams();
    m_pUser = initCapture(hWnd);
}

