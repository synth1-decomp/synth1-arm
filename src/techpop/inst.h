#pragma once

/**
 * @file inst.h
 * @brief CInst, the MIDI instrument interface.
 */

/**
 * @brief MIDI instrument interface.
 *
 * Parses MIDI short messages (processMIDIShortData()) and dispatches them to
 * virtual handlers that a synthesizer overrides. It also tracks the bank
 * number (CC 0 / CC 32), the NRPN number (CC 99 / CC 98) and the data entry
 * bytes (CC 6 / CC 38). The bank-select and program-change enable flags are
 * static and shared by all instances. sizeof == 0x20.
 */
class CInst {
public:
    /**
     * @brief Constructs the parser with a pitch-bend range of 12 and all MIDI state cleared.
     *
     * The enable-flag pointers are set to the shared static flags.
     */
    CInst();

    /**
     * @brief Destroys the instrument; nothing to release.
     */
    virtual ~CInst(){}

    /**
     * @brief Enables or disables bank select messages for all instances.
     *
     * @param b     Nonzero to enable, 0 to disable (stored in s_bEnableBankSelect).
     */
    void enableBankSelect(int b);

    /**
     * @brief Enables or disables program change messages for all instances.
     *
     * @param b     Nonzero to enable, 0 to disable (stored in s_bEnableProgChange).
     */
    void enableProgramChange(int b);

    /**
     * @brief Tells whether bank select messages are handled.
     *
     * @return Nonzero if bank select is enabled, 0 otherwise.
     */
    int getEnableBankSelect();

    /**
     * @brief Tells whether program change messages are handled.
     *
     * @return Nonzero if program change is enabled, 0 otherwise.
     */
    int getEnableProgramChange();

    /**
     * @brief Parses one MIDI short message and calls the matching handler.
     *
     * - Note on (0x9n) calls noteOn(); velocity 0 is treated as note off.
     * - Note off (0x8n) calls noteOff().
     * - Control change (0xBn, controller < 120): handles bank select MSB/LSB
     *   (if enabled), modulation wheel, data entry MSB/LSB, volume, damper
     *   pedal (on at >= 64) and NRPN number, then always calls
     *   processMIDIShortDataIndividual().
     * - Channel mode (0xBn, controller >= 120): all sound off / all notes off
     *   call noteOffAll(), reset all controllers calls resetAllControl().
     * - Program change (0xCn) calls receiveProgramChange() if enabled.
     * - Channel pressure (0xDn) goes to processMIDIShortDataIndividual().
     * - Pitch bend (0xEn) calls setPitchBend() with -8192..8191 and then
     *   processMIDIShortDataIndividual().
     *
     * Other status bytes (e.g. polyphonic key pressure) are ignored. The
     * channel nibble is not checked.
     *
     * @param st    Status byte (message type and channel).
     * @param dt1   First data byte (0..127; notes above 127 are dropped).
     * @param dt2   Second data byte (0..127).
     */
    void processMIDIShortData(unsigned char st, unsigned char dt1, unsigned char dt2);

    /**
     * @brief Stores the data entry MSB (CC 6) and calls changedNRPNData(1).
     *
     * @param v     Data entry MSB (0..127).
     */
    void setDataEntryHI(unsigned char v);

    /**
     * @brief Stores the data entry LSB (CC 38) and calls changedNRPNData(0).
     *
     * @param v     Data entry LSB (0..127).
     */
    void setDataEntryLO(unsigned char v);

    /**
     * @brief Hook for control changes, channel pressure and pitch bend after the generic handling.
     *
     * The base version does nothing.
     *
     * @param st    Status byte.
     * @param dt1   First data byte.
     * @param dt2   Second data byte.
     */
    virtual void processMIDIShortDataIndividual(unsigned char st, unsigned char dt1, unsigned char dt2){}

    /**
     * @brief Starts a note.
     *
     * The base version does nothing.
     *
     * @param nn    MIDI note number (0..127).
     * @param vel   Velocity (1..127).
     */
    virtual void noteOn(int nn, int vel){}

    /**
     * @brief Releases a note.
     *
     * The base version does nothing.
     *
     * @param nn    MIDI note number (0..127).
     */
    virtual void noteOff(int nn){}

    /**
     * @brief Turns the sustain pedal off and sends noteOff() for all 128 notes.
     */
    virtual void noteOffAll();

    /**
     * @brief Starts a note generated by the arpeggiator.
     *
     * The base version does nothing.
     *
     * @param nn    MIDI note number (0..127).
     * @param vel   Velocity.
     */
    virtual void noteOnFromArp(int nn, int vel){}

    /**
     * @brief Releases a note generated by the arpeggiator.
     *
     * The base version does nothing.
     *
     * @param nn    MIDI note number (0..127).
     */
    virtual void noteOffFromArp(int nn){}

    /**
     * @brief Sets the modulation wheel position (CC 1).
     *
     * The base version does nothing.
     *
     * @param v     Wheel position (0..127).
     */
    virtual void setModulationWheel(unsigned char v){}

    /**
     * @brief Called after a data entry byte changes; the base version does nothing.
     *
     * @param bHI   1 if the MSB (CC 6) changed, 0 if the LSB (CC 38) changed.
     */
    virtual void changedNRPNData(int bHI);

    /**
     * @brief Sets the channel volume (CC 7).
     *
     * The base version does nothing.
     *
     * @param v     Volume (0..127).
     */
    virtual void setVolume(unsigned char v){}

    /**
     * @brief Turns the sustain (damper) pedal on or off.
     *
     * The base version does nothing.
     *
     * @param b     Nonzero for on, 0 for off.
     */
    virtual void setSustainEnable(int b){}

    /**
     * @brief Resets pitch bend and modulation wheel to 0 and the NRPN number to 127/127 (null).
     */
    virtual void resetAllControl();

    /**
     * @brief Handles a program change.
     *
     * The base version does nothing.
     *
     * @param progNo    Program number (0..127).
     */
    virtual void receiveProgramChange(int progNo){}

    /**
     * @brief Handles a bank change.
     *
     * The base version does nothing.
     *
     * @param bankNo    Bank number: MSB (CC 0) in bits 8..15, LSB (CC 32) in bits 0..7.
     */
    virtual void receiveBankChange(int bankNo){}

    /**
     * @brief Sets the pitch bend position.
     *
     * The base version does nothing.
     *
     * @param v     Pitch bend (-8192..8191, 0 = center).
     */
    virtual void setPitchBend(short v){}

    static int s_bEnableBankSelect;
    static int s_bEnableProgChange;

protected:
    unsigned char m_NRPNNoMSB;      // +0x08  (CC 99)
    unsigned char m_NRPNNoLSB;      // +0x09  (CC 98)
    unsigned char m_dataEntryLO;    // +0x0a  (CC 38)
    unsigned char m_dataEntryHI;    // +0x0b  (CC 6)
    short m_pitchBendRange;         // +0x0c  (12)
    short m_bankNo;                 // +0x0e  (CC 0 / CC 32)
    int* m_pbEnableBankSelect;      // +0x10  -> s_bEnableBankSelect
    int* m_pbEnableProgChange;      // +0x18  -> s_bEnableProgChange
};
