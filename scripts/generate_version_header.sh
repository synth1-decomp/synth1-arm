#!/bin/sh
# Writes synth1_version.h, the one place the modern build gets its versioning from:
#
#   SYNTH1_VERSION     "1.14.0"       set in src/Version.xcconfig, shown in the plugin window's version label
#   SYNTH1_AU_VERSION  0x00010E00     the Audio Unit version (Synth1.h, and the plugin's Info.plist)
#   SYNTH1_BUILD_ID    "b29256b"      the first 7 characters of the commit ID or "dev"

set -eu

: "${SRCROOT:?set SRCROOT to the folder that holds Synth1.xcodeproj}"
: "${PROJECT_DERIVED_FILE_DIR:?set PROJECT_DERIVED_FILE_DIR to the folder to write synth1_version.h into}"
: "${SYNTH1_VERSION_MAJOR:?set SYNTH1_VERSION_MAJOR, for example 1}"
: "${SYNTH1_VERSION_MINOR:?set SYNTH1_VERSION_MINOR, for example 14}"
: "${SYNTH1_VERSION_BUGFIX:?set SYNTH1_VERSION_BUGFIX, for example 0}"

header="$PROJECT_DERIVED_FILE_DIR/synth1_version.h"

# Checks that a version part is a whole number no larger than the given maximum.
#   $1 = name of the build setting, $2 = maximum
check_part() {
    eval value=\$$1
    case $value in
        ''|*[!0-9]*)
            echo "error: $1 must be a whole number (it is '$value')" >&2
            exit 1 ;;
        0?*)
            echo "error: $1 must not have leading zeros (it is '$value')" >&2
            exit 1 ;;
    esac
    if [ "$value" -gt "$2" ]; then
        echo "error: $1 must be $2 or less (it is $value)" >&2
        exit 1
    fi
}

# The Audio Unit version packs the version as 0xMMMMmmbb: 16 bits major, 8 bits minor, 8 bits bug fix.
check_part SYNTH1_VERSION_MAJOR 65535
check_part SYNTH1_VERSION_MINOR 255
check_part SYNTH1_VERSION_BUGFIX 255
version="$SYNTH1_VERSION_MAJOR.$SYNTH1_VERSION_MINOR.$SYNTH1_VERSION_BUGFIX"
au_version=$(printf '0x%08X' $(( (SYNTH1_VERSION_MAJOR << 16) | (SYNTH1_VERSION_MINOR << 8) | SYNTH1_VERSION_BUGFIX )))

# The build ID comes from build_id in scripts/version.sh, which the installer package name uses too
root="$SRCROOT/.."
. "$root/scripts/version.sh"
id=$(build_id)

contents="// Generated by scripts/generate_version_header.sh; do not edit.
#define SYNTH1_VERSION \"$version\"
#define SYNTH1_AU_VERSION $au_version
#define SYNTH1_BUILD_ID \"$id\""

# Only rewrite the header when something changes. Rewriting it on every build would make Xcode
# recompile everything that includes it, every time.
mkdir -p "$PROJECT_DERIVED_FILE_DIR"
if [ "$(cat "$header" 2>/dev/null)" = "$contents" ]; then
    echo "Version $version ($au_version), build ID $id (unchanged)"
else
    printf '%s\n' "$contents" > "$header"
    echo "Version $version ($au_version), build ID $id"
fi
